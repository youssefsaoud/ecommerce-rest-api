-- Matches existing JPA defaults: nullable fields, varchar(255), numeric(38,2),
-- bigint identity keys, timestamp(6), and the unique cart/user relationship.
-- Email is intentionally not unique: the existing entity has no unique mapping.
CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name varchar(255),
    last_name varchar(255),
    email varchar(255),
    password varchar(255)
);
CREATE TABLE category (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255)
);
CREATE TABLE product (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255),
    description varchar(255),
    price numeric(38,2),
    quantity integer,
    category_id bigint REFERENCES category(id)
);
CREATE TABLE cart (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint UNIQUE REFERENCES users(id)
);
CREATE TABLE cart_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id bigint REFERENCES cart(id),
    product_id bigint REFERENCES product(id),
    quantity integer
);
CREATE TABLE orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint REFERENCES users(id),
    total_amount numeric(38,2),
    created_at timestamp(6)
);
CREATE TABLE order_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint REFERENCES orders(id),
    product_id bigint REFERENCES product(id),
    quantity integer,
    price numeric(38,2)
);
CREATE INDEX idx_users_email ON users(email);
CREATE INDEX idx_product_category ON product(category_id);
CREATE INDEX idx_product_price_id ON product(price, id);
CREATE INDEX idx_cart_item_cart ON cart_item(cart_id);
CREATE INDEX idx_cart_item_product ON cart_item(product_id);
CREATE INDEX idx_orders_user ON orders(user_id);
CREATE INDEX idx_order_item_order ON order_item(order_id);
CREATE INDEX idx_order_item_product ON order_item(product_id);
